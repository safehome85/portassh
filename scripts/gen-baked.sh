#!/bin/sh
# Generates baked.go with fresh ed25519 keys for the given relay server.
#
# Usage:
#   ./scripts/gen-baked.sh <relay-host> [--force]
#
# The script prints the authorized_keys line for the relay and the client
# key accepted by the embedded SSH server.
set -e
cd "$(dirname "$0")/.."

RELAY_HOST="${1:?provide the relay address: ./scripts/gen-baked.sh relay.example.com}"
FORCE="${2:-}"

if [ -f "baked.go" ] && [ "$FORCE" != "--force" ]; then
  echo "ERROR: baked.go already exists." >&2
  echo "To regenerate with new keys (the old ones stop working): $0 $1 --force" >&2
  exit 1
fi

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

ssh-keygen -t ed25519 -N '' -f "$TMP/relay" -C portassh-relay -q
ssh-keygen -t ed25519 -N '' -f "$TMP/host"  -C portassh-host  -q

RPUB_B64=$(base64 < "$TMP/relay" | tr -d '\n')
HPUB_B64=$(base64 < "$TMP/host" | tr -d '\n')
HPUB_LINE=$(cat "$TMP/host.pub")

# relay host key: the real one (if the relay is reachable) or a syntactically
# valid stand-in built from the generated server key (tests only compile it,
# they never dial the relay)
HKLINE=$(ssh-keyscan -t ed25519 "$RELAY_HOST" 2>/dev/null | grep -v '^#' | head -1)
if [ -z "$HKLINE" ]; then
  echo "WARNING: could not read the host key from $RELAY_HOST — a placeholder was written." >&2
  echo "Before real use replace relayHostKeyLine with the output of:" >&2
  echo "  ssh-keyscan -t ed25519 $RELAY_HOST" >&2
  HKLINE="$RELAY_HOST $HPUB_LINE"
fi

# client key: an existing ssh key or a freshly generated one
CPUB=$(cat "$HOME/.ssh/id_ed25519.pub" 2>/dev/null || cat "$HOME/.ssh/id_rsa.pub" 2>/dev/null || true)
if [ -z "$CPUB" ]; then
  ssh-keygen -t ed25519 -N '' -f "$TMP/client" -C portassh-client -q
  CPUB=$(cat "$TMP/client.pub")
  echo "WARNING: no ~/.ssh keys found — generated $TMP/client (save it!)" >&2
fi

# password for connecting from machines without the baked client key
CPASS=$(openssl rand -base64 15 | tr -d '/+=' | head -c 16)

cat > baked.go <<EOF
package main

// Generated by scripts/gen-baked.sh for $RELAY_HOST on $(date +%Y-%m-%d).
// Private keys must never reach the repository (baked.go is gitignored).

const (
	defaultRelay     = "$RELAY_HOST"
	defaultRelayUser = "portassh"
	defaultLPort     = 2222
	defaultRPort     = 2200

	relayPrivKeyB64 = "$RPUB_B64"

	relayHostKeyLine = "$HKLINE"

	serverHostKeyB64 = "$HPUB_B64"
	serverHostPub    = "$HPUB_LINE"

	// парольный вход с машин без ключа (менять можно в любой момент)
	allowedClientPassword = "$CPASS"
)

// клиентские ключи, принимаемые встроенным сервером (слайс не может быть const)
var allowedClientPubKeys = []string{
	"$CPUB",
}
EOF

echo "baked.go created (ed25519 keys)."
echo
echo "=== ONE-TIME RELAY SETUP ($RELAY_HOST) ==="
echo "1) Create the tunnel user and add the key:"
echo "   useradd -m -s /bin/sh portassh"
echo "   mkdir -p /home/portassh/.ssh && chmod 700 /home/portassh/.ssh"
echo "   echo '$(cat "$TMP/relay.pub")' > /home/portassh/.ssh/authorized_keys"
echo "   chown -R portassh:portassh /home/portassh/.ssh"
echo "2) The relay host key is baked into the build: $HKLINE"
echo "3) Connections are accepted only from the machine holding:"
echo "   $CPUB"
echo
echo "Build: ./build.sh"
